-- Referrals: a candidate's or an employer's link or code brings an employer,
-- the employer pays for a plan -- straight away or after time on Free -- and
-- the referrer earns a fixed amount: Starter US$5 monthly or US$20 annual, Growth US$25 monthly or
-- US$100 annual. A later move up earns the difference, so one employer never
-- earns more in total than the best plan it paid for (owner, 22 and 25 Nov
-- 2026).
--
-- Four things are recorded, and each is a fact rather than a balance -- the
-- rule the discovery quota set (C.3): a number kept in a column drifts from
-- what happened, and drifting here is paying for nothing or not paying for
-- something.
--
--   * who arrived through whose link (referral_visits), kept so that a
--     complaint about a link pasted somewhere it should not have been can be
--     traced to where the traffic came from;
--   * which employer account a link produced (employers.referred_by_*),
--     written once, at sign-up, and never changed afterwards;
--   * what was earned (referral_earnings): one row per plan and billing
--     period an employer paid for -- a *claim* carrying that plan's full
--     worth, with its own sixty days. When a claim confirms it pays only what
--     takes the employer's total up to the best worth confirmed so far, so
--     the total is always the best plan kept for sixty days, whatever order
--     plans were bought, dropped and bought again in (26 Nov 2026; storing
--     only the difference at purchase time broke in a new way at every
--     review). The unique index is what makes a redelivered webhook, or a
--     cancel-and-subscribe-again, claim nothing twice;
--   * where the referrer wants to be paid (payout_paypal_email, on candidates
--     and on employers): PayPal only, paid by hand from the admin screen;
--     nothing here moves money.

-- Every referral code, whoever owns it: a candidate or, since 25 Nov 2026, an
-- employer. Both are paid the same way, by PayPal.
-- One table rather than a column on each, because a code is typed into one
-- field and has to mean exactly one person -- two unique indexes on two
-- tables cannot stop a candidate and an employer drawing the same eight
-- characters. Generated by the site the first time the owner opens their
-- referral page, so accounts that never refer anybody have none.
create table referral_codes (
    code          text        primary key,
    candidate_id  bigint      unique references candidates (id) on delete cascade,
    employer_id   bigint      unique references employers (id) on delete cascade,
    created_at    timestamptz not null default now(),
    check (num_nonnulls(candidate_id, employer_id) = 1)
);

-- The PayPal account the referrer wants earnings sent to. Theirs to set and
-- change; copied onto the earning at the moment it is paid, so a later change
-- never rewrites where an old payment went. Employers are paid in money too,
-- not in credit on their plan (owner, 25 Nov 2026): an employer who refers
-- ten others would otherwise stop paying for years.
alter table candidates
    add column payout_paypal_email text,
    add column payout_email_set_at timestamptz;
alter table employers
    add column payout_paypal_email text,
    add column payout_email_set_at timestamptz;

create table referral_visits (
    id            bigserial   primary key,
    candidate_id  bigint      references candidates (id) on delete cascade,
    employer_id   bigint      references employers (id) on delete cascade,
    visited_at    timestamptz not null default now(),
    -- The host only, never the full referrer: enough to see "reddit.com" or
    -- "mail.google.com", and nothing about the visitor beyond that.
    referer_host  text,
    check (num_nonnulls(candidate_id, employer_id) = 1)
);
create index referral_visits_by_candidate on referral_visits (candidate_id, visited_at desc);
create index referral_visits_by_employer on referral_visits (employer_id, visited_at desc)
 where employer_id is not null;

-- Set null when the referrer deletes their account: the employer stays, the
-- tie to a person who has left does not.
alter table employers
    add column referred_by_candidate_id bigint references candidates (id) on delete set null,
    -- Or another employer's link. Never both, and never itself.
    add column referred_by_employer_id bigint references employers (id) on delete set null,
    add column referred_at timestamptz,
    -- How the tie was made: the link's cookie, or the code typed into the
    -- sign-up form when no link carried it. For the operator, to see which of
    -- the two actually brings people.
    add column referred_via text check (referred_via in ('LINK', 'CODE')),
    -- When the referrer was told that somebody signed up through their link.
    add column referral_notified_at timestamptz;
alter table employers add constraint employers_one_referrer
    check (num_nonnulls(referred_by_candidate_id, referred_by_employer_id) <= 1
           and (referred_by_employer_id is null or referred_by_employer_id <> id));
create index employers_referred_by on employers (referred_by_candidate_id)
 where referred_by_candidate_id is not null;
create index employers_referred_by_employer on employers (referred_by_employer_id)
 where referred_by_employer_id is not null;

create table referral_earnings (
    id               bigserial   primary key,
    -- Who earns it: the candidate, or the employer whose link it was. Copied
    -- from the referred employer when earned; set null if that account goes,
    -- so neither is required.
    candidate_id     bigint      references candidates (id) on delete set null,
    referrer_employer_id bigint  references employers (id) on delete set null,
    -- The account that paid for the plan.
    employer_id      bigint      not null references employers (id) on delete cascade,
    -- The Stripe subscription that earned it, to check against at payout.
    subscription_ref text,
    plan             text        not null,
    cycle            text        not null check (cycle in ('MONTHLY', 'ANNUAL')),
    -- The plan and period's full worth (Starter $5/$20, Growth $25/$100).
    worth_cents      integer     not null check (worth_cents > 0),
    -- What this claim pays: an estimate while PENDING (worth less the best
    -- claim standing before it), fixed for good when it settles CONFIRMED
    -- (worth less the best worth already confirmed or paid). Zero when a
    -- better plan already covers it.
    amount_cents     integer     not null check (amount_cents >= 0),
    currency         text        not null default 'USD',
    created_at       timestamptz not null default now(),
    -- Not payable before this: sixty days after the first real charge, and
    -- only if the plan is still running then. A subscription that starts with
    -- a free month counts from the end of that month, because until then
    -- nobody has paid anything.
    confirms_at      timestamptz not null,
    -- PENDING until confirms_at; then settled once, for good, by the
    -- pipeline (ReferralNotifier.settle): CONFIRMED if the plan or a better
    -- one ran to that day, LAPSED if not. Settled rather than worked out on
    -- every read, because the subscription row is rewritten in place when the
    -- employer changes plan: re-reading it later would let a move down
    -- after the day take back a commission already confirmed, and a return
    -- months later revive one that lapsed.
    status           text        not null default 'PENDING'
                     check (status in ('PENDING', 'CONFIRMED', 'LAPSED', 'PAID', 'VOID')),
    settled_at       timestamptz,
    -- When the referrer was told the employer subscribed, and when they were
    -- told the earning confirmed. ReferralNotifier claims each before sending.
    subscribed_notified_at timestamptz,
    confirmed_notified_at timestamptz,
    paid_at          timestamptz,
    -- Where it went and the PayPal transaction id, written by whoever paid it.
    paid_to          text,
    paid_reference   text,
    voided_at        timestamptz,
    void_reason      text,
    note             text
);
-- Once per employer, plan and cycle -- except a lapsed one, which earned
-- nothing: an employer who cancelled inside the sixty days and comes back
-- later earns that plan then, with a sixty-day hold of its own.
create unique index referral_earnings_once on referral_earnings (employer_id, plan, cycle)
 where status <> 'LAPSED';
alter table referral_earnings add constraint referral_earnings_one_referrer
    check (num_nonnulls(candidate_id, referrer_employer_id) <= 1);
create index referral_earnings_by_candidate on referral_earnings (candidate_id, created_at desc);
create index referral_earnings_by_referrer_employer on referral_earnings (referrer_employer_id, created_at desc)
 where referrer_employer_id is not null;
