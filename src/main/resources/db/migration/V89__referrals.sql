-- Referrals: a candidate's link or code brings an employer, the employer pays
-- for a plan -- straight away or after time on Free -- and the candidate earns
-- a fixed amount: Starter US$5 monthly or US$20 annual, Growth US$25 monthly or
-- US$100 annual. A later move up earns the difference, so one employer never
-- earns more in total than the best plan it paid for (owner, 22 and 25 Nov
-- 2026).
--
-- Four things are recorded, and each is a fact rather than a balance -- the
-- rule the discovery quota set (C.3): a number kept in a column drifts from
-- what happened, and drifting here is paying for nothing or not paying for
-- something.
--
--   * who arrived through whose link (referral_visits), kept so that a
--     complaint about a link pasted somewhere it should not have been can be
--     traced to where the traffic came from;
--   * which employer account a link produced (employers.referred_by_*),
--     written once, at sign-up, and never changed afterwards;
--   * what was earned (referral_earnings): one row per plan and cycle an
--     employer first paid for, each holding only what it added over the rows
--     before it. At most one row per employer, plan and cycle, ever -- the
--     unique index is the rule, and it is also what makes a redelivered
--     webhook, or a cancel-and-subscribe-again, earn nothing twice;
--   * where the candidate wants to be paid (candidates.payout_paypal_email).
--     PayPal only, paid by hand from the admin screen; nothing here moves
--     money.

-- The code in the link. Generated by the site the first time the candidate
-- opens the referral section, so accounts that never refer anybody carry none.
alter table candidates
    add column referral_code text,
    -- The PayPal account the candidate wants earnings sent to. Theirs to set
    -- and change; copied onto the earning at the moment it is paid, so a
    -- later change never rewrites where an old payment went.
    add column payout_paypal_email text,
    add column payout_email_set_at timestamptz;
create unique index candidates_referral_code on candidates (referral_code)
 where referral_code is not null;

create table referral_visits (
    id            bigserial   primary key,
    candidate_id  bigint      not null references candidates (id) on delete cascade,
    visited_at    timestamptz not null default now(),
    -- The host only, never the full referrer: enough to see "reddit.com" or
    -- "mail.google.com", and nothing about the visitor beyond that.
    referer_host  text
);
create index referral_visits_by_candidate on referral_visits (candidate_id, visited_at desc);

-- Set null when the candidate deletes their account: the employer stays, the
-- tie to a person who has left does not.
alter table employers
    add column referred_by_candidate_id bigint references candidates (id) on delete set null,
    add column referred_at timestamptz,
    -- How the tie was made: the link's cookie, or the code typed into the
    -- sign-up form when no link carried it. For the operator, to see which of
    -- the two actually brings people.
    add column referred_via text check (referred_via in ('LINK', 'CODE')),
    -- When the referrer was told that somebody signed up through their link.
    add column referral_notified_at timestamptz;
create index employers_referred_by on employers (referred_by_candidate_id)
 where referred_by_candidate_id is not null;

create table referral_earnings (
    id               bigserial   primary key,
    candidate_id     bigint      references candidates (id) on delete set null,
    employer_id      bigint      not null references employers (id) on delete cascade,
    -- The Stripe subscription that earned it, to check against at payout.
    subscription_ref text,
    plan             text        not null,
    cycle            text        not null check (cycle in ('MONTHLY', 'ANNUAL')),
    amount_cents     integer     not null check (amount_cents > 0),
    currency         text        not null default 'USD',
    created_at       timestamptz not null default now(),
    -- Not payable before this: sixty days after the first real charge, and
    -- only if the plan is still running then. A subscription that starts with
    -- a free month counts from the end of that month, because until then
    -- nobody has paid anything.
    confirms_at      timestamptz not null,
    status           text        not null default 'PENDING'
                     check (status in ('PENDING', 'PAID', 'VOID')),
    -- When the referrer was told the employer subscribed, and when they were
    -- told the earning confirmed. ReferralNotifier claims each before sending.
    subscribed_notified_at timestamptz,
    confirmed_notified_at timestamptz,
    paid_at          timestamptz,
    -- Where it went and the PayPal transaction id, written by whoever paid it.
    paid_to          text,
    paid_reference   text,
    voided_at        timestamptz,
    void_reason      text,
    note             text
);
create unique index referral_earnings_once on referral_earnings (employer_id, plan, cycle);
create index referral_earnings_by_candidate on referral_earnings (candidate_id, created_at desc);
